    <section>
      <h2 class="font-bold text-gray-800 mb-1">1. About this system</h2>
      <p>Smart Campus lets students and staff of ACLC College report safety incidents, view incident status, find emergency contacts, see campus risk analysis, and chat with Medai, an AI safety assistant. This policy explains what information the system collects, why, and your choices.</p>
    </section>

    <section>
      <h2 class="font-bold text-gray-800 mb-1">2. Information we collect</h2>
      <ul class="list-disc pl-5 space-y-1">
        <li><strong>Account details:</strong> first, middle and last name, email, and your password (stored only as a secure hash, never in plain text).</li>
        <li><strong>Optional profile details:</strong> phone number, department/course, student or employee ID, bio, profile photo, and appearance (light/dark) preference.</li>
        <li><strong>Incident reports:</strong> incident type, severity, branch, location, description, optional photo, time of report, your name and account (unless you choose to submit anonymously), and the status and admin notes added later.</li>
        <li><strong>Security data:</strong> your IP address and email used in sign-in and sign-up attempts, to limit repeated failed attempts. These records are deleted automatically after about one day.</li>
        <li><strong>Cookies and local storage:</strong> a session cookie to keep you signed in, a theme cookie, an optional "Remember Me" cookie that stores your email for 30 days, and your Medai chat history in your browser.</li>
      </ul>
    </section>

    <section>
      <h2 class="font-bold text-gray-800 mb-1">3. How we use it</h2>
      <ul class="list-disc pl-5 space-y-1">
        <li>To create and secure your account and sign you in.</li>
        <li>To record, track and resolve incidents, and let reporters see updates on their reports.</li>
        <li>To compute campus risk scores by location and incident type from past reports.</li>
        <li>To show emergency contacts and give safety guidance.</li>
        <li>To prevent abuse, such as repeated login attempts, spam sign-ups and excessive Medai reports.</li>
      </ul>
    </section>

    <section>
      <h2 class="font-bold text-gray-800 mb-1">4. Who can see your information</h2>
      <ul class="list-disc pl-5 space-y-1">
        <li><strong>Campus administrators</strong> can view incident reports, the user list (name, email, role, join date), and can update, resolve or delete reports and accounts.</li>
        <li><strong>Other signed-in users</strong> can see the incident list, including description, location, status, reporter name, photo and admin notes. Do not include sensitive personal details in descriptions or photos. Use the anonymous option if you do not want your name shown.</li>
        <li>Your password, email and phone number are not shown to other regular users.</li>
        <li>We do not sell your information.</li>
      </ul>
    </section>

    <section>
      <h2 class="font-bold text-gray-800 mb-1">5. AI features (Medai, severity suggestion, voice reports, risk briefing)</h2>
      <ul class="list-disc pl-5 space-y-1">
        <li>These features send text to an external AI provider (Groq) to generate a response. This includes your chat messages, incident descriptions or voice transcripts you submit to the feature, and campus data such as incident counts, recent unresolved incidents, locations, emergency contacts, and aggregated risk scores.</li>
        <li>Your password, email, phone number and other reporters' names are not sent.</li>
        <li>Medai chat history is stored only in your browser. Clear it with the 🗑 button in the chat. Chat messages are not saved on our server.</li>
        <li>Reports filed through Medai are saved like any other report, marked "[via Medai]", and only after you confirm.</li>
        <li>AI can make mistakes. It is not a substitute for emergency services. In a real emergency, call the emergency numbers right away.</li>
        <li>You can turn off AI severity suggestion in the report form and choose severity manually.</li>
      </ul>
    </section>

    <section>
      <h2 class="font-bold text-gray-800 mb-1">6. Third-party services</h2>
      <p>Besides the AI provider, pages load fonts and styling from Google Fonts and the Tailwind CDN, which may receive your IP address and browser details when the page loads.</p>
    </section>

    <section>
      <h2 class="font-bold text-gray-800 mb-1">7. Data retention and security</h2>
      <ul class="list-disc pl-5 space-y-1">
        <li>Account and incident records are kept until deleted by you through an administrator or by an administrator.</li>
        <li>Passwords are hashed, sign-in attempts are rate-limited, and forms use CSRF protection. No system is completely secure, so please use a strong, unique password and sign out on shared computers.</li>
      </ul>
    </section>

    <section>
      <h2 class="font-bold text-gray-800 mb-1">8. Your choices and rights</h2>
      <ul class="list-disc pl-5 space-y-1">
        <li>Edit your profile details, photo and password anytime in Profile &amp; Settings.</li>
        <li>Report anonymously, and skip optional fields.</li>
        <li>Uncheck "Remember Me" to avoid storing your email in a cookie.</li>
        <li>Ask the system administrator to correct or delete your account or reports. Under the Philippine Data Privacy Act of 2012, you may also ask about the personal data we hold about you and raise concerns about how it is handled.</li>
      </ul>
    </section>


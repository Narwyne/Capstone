    <section>
      <h2 class="font-bold text-gray-800 mb-1">1. What is Medai?</h2>
      <p>Medai is the AI-powered campus safety assistant in this system. It answers safety questions, gives basic emergency guidance, shows emergency contacts, and can help you file an incident report. It also powers the AI severity suggestion and the voice-report feature.</p>
    </section>

    <section>
      <h2 class="font-bold text-gray-800 mb-1">2. Information Medai uses</h2>
      <ul class="list-disc pl-5 space-y-1">
        <li><strong>Your messages</strong> to Medai (only your last few messages are kept in the conversation context).</li>
        <li><strong>Campus data</strong> added to each request so answers are accurate: incident counts, recent unresolved incidents (type, severity, location, time, status, admin notes), available report types and locations, and emergency contacts.</li>
        <li><strong>Report details</strong> you confirm through Medai (type, severity, branch, location, description). Reports filed this way are saved under your account and marked "[via Medai]".</li>
        <li><strong>Voice reports and AI severity:</strong> the text transcript of what you say, or the description you type, is analyzed to suggest report fields.</li>
      </ul>
      <p class="mt-1">Medai does not receive your password, email, phone number, or the names of other reporters.</p>
    </section>

    <section>
      <h2 class="font-bold text-gray-800 mb-1">2a. Where it is stored</h2>
      <ul class="list-disc pl-5 space-y-1">
        <li><strong>In your browser:</strong> your Medai chat history is saved in your browser's local storage so it stays after a refresh. Use the 🗑 button in the chat to delete it. On a shared computer, clear it before leaving.</li>
        <li><strong>On our server:</strong> chat messages are not saved. Only incident reports you submit (including through Medai) are stored in the system database.</li>
      </ul>
    </section>

    <section>
      <h2 class="font-bold text-gray-800 mb-1">3. Third-party AI provider</h2>
      <p>Medai's replies are generated by an external AI service (Groq). Your messages and the campus data listed above are sent to that service to produce a response. Do not share sensitive personal information (such as passwords, ID numbers, or health records) in the chat.</p>
    </section>

    <section>
      <h2 class="font-bold text-gray-800 mb-1">4. How the information is used</h2>
      <ul class="list-disc pl-5 space-y-1">
        <li>To answer your questions and give safety guidance.</li>
        <li>To file incident reports you approve (Medai always asks for confirmation before submitting).</li>
        <li>To suggest severity levels and fill in voice reports, which you can review before submitting.</li>
        <li>Reports are visible to campus administrators and, as described in the incident list, to other signed-in users. You may submit anonymously through the report form.</li>
      </ul>
    </section>

    <section>
      <h2 class="font-bold text-gray-800 mb-1">5. Limits of Medai</h2>
      <ul class="list-disc pl-5 space-y-1">
        <li>Medai is an AI and can make mistakes. It is <strong>not</strong> a substitute for emergency services, medical professionals, or campus security.</li>
        <li>In a real emergency, call the emergency numbers shown by Medai or on the Emergency Services page immediately.</li>
        <li>Medai is not monitored in real time. Reports filed through it are reviewed by administrators later.</li>
        <li>Medai is limited in how many reports it can file per hour to prevent misuse.</li>
      </ul>
    </section>

    <section>
      <h2 class="font-bold text-gray-800 mb-1">6. Your choices</h2>
      <ul class="list-disc pl-5 space-y-1">
        <li>Clear your chat history anytime with the 🗑 button.</li>
        <li>Turn off "Let AI suggest severity" in the report form and choose severity manually.</li>
        <li>Choose not to use Medai; you can still report incidents through the report form.</li>
        <li>To ask about or request removal of a report you submitted, contact the campus administrator.</li>
      </ul>
    </section>

    <section>
